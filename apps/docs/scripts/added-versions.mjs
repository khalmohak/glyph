// Regenerates src/lib/added.ts: the release each docs entry first shipped in, from git history.
// The first commit that added `content/<slug>/meta.ts` maps to the oldest @glyphui/ui release
// tag containing it; entries not in any release yet get `next` (the version being prepared).
//
//   node apps/docs/scripts/added-versions.mjs 0.8.0
import { execFileSync } from 'node:child_process'
import { existsSync, readdirSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const next = process.argv[2]
if (!next) throw new Error('Pass the upcoming version, e.g. 0.8.0')
const docs = join(dirname(fileURLToPath(import.meta.url)), '..')
const git = (...args) => execFileSync('git', args, { cwd: docs, encoding: 'utf8' }).trim()
const semver = (t) => t.split('@').pop().split('.').map(Number)
const tags = git('tag', '-l', '@glyphui/ui@*')
  .split('\n')
  .filter(Boolean)
  .sort((a, b) => {
    const [x, y] = [semver(a), semver(b)]
    return x[0] - y[0] || x[1] - y[1] || x[2] - y[2]
  })

const content = join(docs, 'src/content')
const added = {}
for (const dir of readdirSync(content, { withFileTypes: true })) {
  if (!dir.isDirectory() || !existsSync(join(content, dir.name, 'meta.ts'))) continue
  const commits = git(
    'log',
    '--diff-filter=A',
    '--format=%H',
    '--',
    `src/content/${dir.name}/meta.ts`,
  )
  const first = commits.split('\n').filter(Boolean).pop()
  let version = next
  for (const tag of first ? tags : []) {
    try {
      git('merge-base', '--is-ancestor', first, tag)
      version = tag.split('@').pop()
      break
    } catch {}
  }
  added[dir.name] = version
}

const body = Object.entries(added)
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([slug, version]) => `  '${slug}': '${version}',`)
  .join('\n')
writeFileSync(
  join(docs, 'src/lib/added.ts'),
  `// Generated by scripts/added-versions.mjs. Do not edit by hand.

/** The release each docs entry first shipped in. */
export const addedIn: Record<string, string> = {
${body}
}

/** The newest release: entries added in it get a "new" badge. */
export const latest = '${next}'

const minor = (version: string) => version.split('.').slice(0, 2).join('.')

/** Added in the latest minor release. */
export function isNew(slug: string): boolean {
  const version = addedIn[slug]
  return version !== undefined && minor(version) === minor(latest)
}
`,
)
console.log(`Wrote src/lib/added.ts (${Object.keys(added).length} entries)`)
